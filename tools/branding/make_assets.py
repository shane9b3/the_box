"""Branding pipeline: design/logo/The_Box.png -> vectors + rasters under app/src/main/res (the wordmark under ui/src/main/res).

Tracing: sub-pixel marching squares (skimage.find_contours at the 50 % level of the
anti-aliased ink field) + Douglas-Peucker simplification. Paths are even-odd polygons.
"""
import sys, pathlib
import numpy as np
from PIL import Image, ImageDraw
from skimage import measure

root = pathlib.Path(sys.argv[1])
preview = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 and sys.argv[2] else None
res = root / "app/src/main/res"
ui_res = root / "ui/src/main/res"  # the guide header (:ui) draws the wordmark (design §3.17, §2.13 item 16)
BG = (0x0A, 0x0D, 0x13)
DENS = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}
FRAME_MIN_X = 148  # contours left of this are the rotated "The"

src = Image.open(root / "design/logo/The_Box.png").convert("RGBA")
W, H = src.size
white = Image.new("RGBA", src.size, (255, 255, 255, 255))
gray = np.asarray(Image.alpha_composite(white, src).convert("L"), dtype=np.float32)

# ---- ink alpha (white-on-transparent wordmark) ----------------------------------------
alpha = np.clip((230.0 - gray) / 200.0, 0, 1)


def ink_image(a):
    out = np.zeros(a.shape + (4,), np.uint8)
    out[..., :3] = 255
    out[..., 3] = (a * 255 + 0.5).astype(np.uint8)
    return Image.fromarray(out, "RGBA")


# ---- trace ----------------------------------------------------------------------------
field = np.pad(1.0 - gray / 255.0, 1)  # ink = 1
polys = []
for c in measure.find_contours(field, 0.5):
    c = measure.approximate_polygon(c, 0.55)[:-1]
    if len(c) < 3:
        continue
    pts = np.stack([c[:, 1] - 1, c[:, 0] - 1], 1)  # x, y in source px
    area = 0.5 * np.sum(pts[:, 0] * np.roll(pts[:, 1], -1) - np.roll(pts[:, 0], -1) * pts[:, 1])
    if abs(area) < 12:
        continue  # specks
    polys.append(pts)
frame_polys = [p for p in polys if p[:, 0].min() > FRAME_MIN_X]
outer = max(frame_polys, key=lambda p: np.ptp(p[:, 0]))
fx0, fy0 = outer.min(0)
fx1, fy1 = outer.max(0)
fw, fh = fx1 - fx0, fy1 - fy0


def num(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def path_data(ps, tf):
    parts = []
    for p in ps:
        q = [tf(x, y) for x, y in p]
        parts.append("M" + " ".join(num(x) + "," + num(y) for x, y in q) + "Z")
    return "".join(parts)


def vector(path, vw, vh, dw, dh, comment):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/branding/make-assets.sh; do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{dw}dp"
    android:height="{dh}dp"
    android:viewportWidth="{vw}"
    android:viewportHeight="{vh}">
    <path
        android:fillColor="#FFFFFF"
        android:fillType="evenOdd"
        android:pathData="{path}" />
</vector>
"""


# ---- vectors --------------------------------------------------------------------------
(res / "drawable").mkdir(parents=True, exist_ok=True)
(ui_res / "drawable").mkdir(parents=True, exist_ok=True)
(ui_res / "drawable/wordmark.xml").write_text(vector(
    path_data(polys, lambda x, y: (x, y)), W, H, 96, round(96 * H / W, 1),
    "Monochrome wordmark (white); tint at the use site."))

FG_W = 58.0  # dp, frame width inside the 108 dp canvas (66 dp safe circle: 58 x 27.2 fits)
s = FG_W / fw
cx, cy = (fx0 + fx1) / 2, (fy0 + fy1) / 2


def fg_tf(x, y):
    return 54 + (x - cx) * s, 54 + (y - cy) * s


(res / "drawable/ic_launcher_foreground.xml").write_text(vector(
    path_data(frame_polys, fg_tf), 108, 108, 108, 108,
    "Adaptive icon foreground: rounded box frame with \"Box\" only, inside the 66 dp safe zone."))
(res / "drawable/ic_launcher_background.xml").write_text("""<?xml version="1.0" encoding="utf-8"?>
<!-- Adaptive icon background: base colour #0A0D13. Generated by tools/branding/make-assets.sh. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#0A0D13"
        android:pathData="M0,0h108v108h-108z" />
</vector>
""")
adaptive = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""
(res / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
(res / "mipmap-anydpi-v26/ic_launcher.xml").write_text(adaptive)
(res / "mipmap-anydpi-v26/ic_launcher_round.xml").write_text(adaptive)

# ---- rasters --------------------------------------------------------------------------
wordmark = ink_image(alpha)
frame_crop = ink_image(alpha[max(0, int(fy0) - 2):int(fy1) + 3, max(0, int(fx0) - 2):int(fx1) + 3])


def fit(img, w):
    h = round(img.height * w / img.width)
    return img.resize((max(1, round(w)), max(1, h)), Image.LANCZOS)


def paste_center(canvas, img):
    canvas.alpha_composite(img, ((canvas.width - img.width) // 2, (canvas.height - img.height) // 2))


banners = {}
for d, k in DENS.items():
    bw, bh, pad = round(320 * k), round(180 * k), round(24 * k)
    cv = Image.new("RGBA", (bw, bh), BG + (255,))
    paste_center(cv, fit(wordmark, min(bw - 2 * pad, (bh - 2 * pad) * W / H)))
    out = res / f"drawable-{d}"
    out.mkdir(exist_ok=True)
    cv.convert("RGB").save(out / "banner.png", optimize=True)
    banners[d] = cv


def legacy(px, round_):
    ss = 4
    n = px * ss
    mask = Image.new("L", (n, n), 0)
    dr = ImageDraw.Draw(mask)
    if round_:
        dr.ellipse((0, 0, n - 1, n - 1), fill=255)
    else:
        dr.rounded_rectangle((0, 0, n - 1, n - 1), radius=n * 0.16, fill=255)
    mask = mask.resize((px, px), Image.LANCZOS)
    cv = Image.new("RGBA", (px, px), BG + (255,))
    paste_center(cv, fit(frame_crop, px * (0.60 if round_ else 0.66)))
    cv.putalpha(mask)
    return cv


for d, k in DENS.items():
    out = res / f"mipmap-{d}"
    out.mkdir(exist_ok=True)
    px = round(48 * k)
    legacy(px, False).save(out / "ic_launcher.png", optimize=True)
    legacy(px, True).save(out / "ic_launcher_round.png", optimize=True)

# ---- previews (optional) --------------------------------------------------------------
if preview:
    preview.mkdir(parents=True, exist_ok=True)
    for d, cv in banners.items():
        cv.convert("RGB").save(preview / f"banner-{d}.png")
    # Foreground rendered from the traced vector paths (even-odd), 108 dp canvas at 192 px
    n, ss = 192, 4
    acc = np.zeros((n * ss, n * ss), bool)
    for p in frame_polys:
        m = Image.new("1", (n * ss, n * ss), 0)
        pts = np.array([fg_tf(x, y) for x, y in p]) * n * ss / 108
        ImageDraw.Draw(m).polygon([tuple(v) for v in pts], fill=1)
        acc ^= np.asarray(m, bool)
    fgm = Image.fromarray((acc * 255).astype(np.uint8)).resize((n, n), Image.LANCZOS)
    cv = Image.new("RGBA", (n, n), BG + (255,))
    cv.paste(Image.new("RGBA", (n, n), (255, 255, 255, 255)), (0, 0), fgm)
    cv.convert("RGB").save(preview / "foreground-192.png")
    circ = Image.new("L", (n, n), 0)
    ImageDraw.Draw(circ).ellipse((n * 21 / 108, n * 21 / 108, n * 87 / 108, n * 87 / 108), outline=255)
    chk = cv.convert("RGB")
    chk.paste((255, 80, 80), (0, 0), circ)
    chk.save(preview / "foreground-192-safezone.png")
    legacy(192, False).save(preview / "legacy-192.png")
    legacy(192, True).save(preview / "legacy-round-192.png")
print(f"traced {len(polys)} contours ({len(frame_polys)} in frame); frame bbox {fw:.0f}x{fh:.0f}")
