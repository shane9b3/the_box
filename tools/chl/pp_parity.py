#!/usr/bin/env python3
"""Second-by-second dump of the reference power-play model (tools/chl/pp_replay.py), for the Kotlin parity test.

`ChlPowerPlayReplayTest.theModelAgreesWithTheReferenceAtEverySecond` (core) runs the Kotlin model
(`ChlPowerPlay.Model`) on the same recorded games and asserts it agrees with this dump at every second: the advantaged side, the kind, the seat end (seconds remaining = end - t) and
the H9 hidden flag. The dump is run-length encoded: one line per stretch with an unchanged state.

Usage (from the repo root):
  python3 -I tools/chl/pp_parity.py > core/src/test/resources/sports/chl/pp-parity-2026-11-13.tsv

Lines:
  G <league> <game id> <end>                    one game; the model runs from 0 to <end> inclusive (Sim.end)
  S <from> <to> <adv> <kind> <seat end> <hidden> a stretch of seconds [from, to] in the game above; adv '-' = even
                                                (kind, end and hidden are then '-')
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pp_replay as ref  # noqa: E402  (the reference model, unchanged)


def main():
    d = ref.DEFAULT_DIR
    print("# generated by tools/chl/pp_parity.py from", d)
    for league in ref.LEAGUES:
        pen_all = ref.load(d, league, "penalties")
        for gid in sorted(pen_all, key=int):
            pens, goals = ref.game_inputs(d, league, gid)
            sim = ref.Sim(ref.counted_rows(pens), goals, ref.h9_windows(pens))
            print("G", league, gid, sim.end)
            run = None
            for t in range(0, sim.end + 1):
                st = sim.state(t)
                key = ("-", "-", "-", "-") if st is None else (st[0], st[1], st[2] + t, int(bool(st[3])))
                if run is not None and run[2] == key:
                    run[1] = t
                else:
                    if run is not None:
                        print("S", run[0], run[1], *run[2])
                    run = [t, t, key]
            if run is not None:
                print("S", run[0], run[1], *run[2])


if __name__ == "__main__":
    main()
