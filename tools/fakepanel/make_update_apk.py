#!/usr/bin/env python3
"""make_update_apk - build the updater fixtures for I-M5-19 (docs/design/m5-setup-settings.md §6.3) without Gradle.

    python3 tools/fakepanel/make_update_apk.py IN.apk OUT.apk --version-code 2 [--keystore KS --alias A --pass P]

Rewrites `versionCode` in the APK's binary AndroidManifest.xml, re-zips every other entry unchanged (same compression),
then `zipalign -p 4` and `apksigner sign` from the newest $ANDROID_HOME/build-tools. Without --keystore it signs with
the Android debug key (~/.android/debug.keystore, the key Gradle signs debug builds with); `--new-key` signs with a
throwaway key generated by keytool (the "another signer" fixture). Test tool only.
"""
import argparse
import glob
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import zipfile

VERSION_CODE_ATTR = 0x0101021B
RES_XML_START_ELEMENT = 0x0102
RES_XML_RESOURCE_MAP = 0x0180
TYPE_INT_DEC = 0x10


def patch_version_code(axml: bytes, code: int) -> bytes:
    """Sets android:versionCode on the <manifest> element of a binary XML document."""
    b = bytearray(axml)
    _, header_size, total = struct.unpack_from("<HHI", b, 0)
    off = header_size
    attr_ids = []
    while off < total:
        ctype, chsize, csize = struct.unpack_from("<HHI", b, off)
        if ctype == RES_XML_RESOURCE_MAP:
            n = (csize - chsize) // 4
            attr_ids = list(struct.unpack_from("<%dI" % n, b, off + chsize))
        elif ctype == RES_XML_START_ELEMENT:
            ext = off + chsize  # ResXMLTree_attrExt
            attr_start, attr_size, attr_count = struct.unpack_from("<HHH", b, ext + 8)
            for i in range(attr_count):
                a = ext + attr_start + i * attr_size
                name_idx = struct.unpack_from("<I", b, a + 4)[0]
                if name_idx < len(attr_ids) and attr_ids[name_idx] == VERSION_CODE_ATTR:
                    struct.pack_into("<I", b, a + 8, 0xFFFFFFFF)            # rawValue: none
                    struct.pack_into("<HBB", b, a + 12, 8, 0, TYPE_INT_DEC)  # Res_value size, res0, dataType
                    struct.pack_into("<I", b, a + 16, code)
                    return bytes(b)
            raise ValueError("first element has no versionCode attribute")
        off += csize
    raise ValueError("no start element found")


def build_tools():
    home = os.environ.get("ANDROID_HOME") or os.path.expanduser("~/Library/Android/sdk")
    dirs = sorted(glob.glob(os.path.join(home, "build-tools", "*")))
    if not dirs:
        sys.exit("no $ANDROID_HOME/build-tools")
    return dirs[-1]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("inp")
    ap.add_argument("out")
    ap.add_argument("--version-code", type=int, required=True)
    ap.add_argument("--keystore", default=os.path.expanduser("~/.android/debug.keystore"))
    ap.add_argument("--alias", default="androiddebugkey")
    ap.add_argument("--pass", dest="password", default="android")
    ap.add_argument("--new-key", action="store_true", help="sign with a throwaway key (another signer)")
    a = ap.parse_args(argv)

    bt = build_tools()
    work = tempfile.mkdtemp(prefix="thebox-apk-")
    try:
        unaligned = os.path.join(work, "unaligned.apk")
        with zipfile.ZipFile(a.inp) as zin, zipfile.ZipFile(unaligned, "w") as zout:
            for info in zin.infolist():
                if info.filename.startswith("META-INF/") and info.filename.upper().endswith((".SF", ".RSA", ".EC", ".MF")):
                    continue  # old v1 signature
                data = zin.read(info.filename)
                if info.filename == "AndroidManifest.xml":
                    data = patch_version_code(data, a.version_code)
                zi = zipfile.ZipInfo(info.filename, info.date_time)
                zi.compress_type = info.compress_type
                zi.external_attr = info.external_attr
                zout.writestr(zi, data)
        aligned = os.path.join(work, "aligned.apk")
        subprocess.run([os.path.join(bt, "zipalign"), "-f", "-p", "4", unaligned, aligned], check=True)
        ks, alias, pw = a.keystore, a.alias, a.password
        if a.new_key:
            ks, alias, pw = os.path.join(work, "other.jks"), "other", "otherpass"
            subprocess.run(["keytool", "-genkeypair", "-keystore", ks, "-alias", alias, "-storepass", pw, "-keypass", pw,
                            "-keyalg", "RSA", "-keysize", "2048", "-validity", "3650", "-dname", "CN=Not The Box"],
                           check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        subprocess.run([os.path.join(bt, "apksigner"), "sign", "--ks", ks, "--ks-key-alias", alias, "--ks-pass", "pass:" + pw,
                        "--key-pass", "pass:" + pw, "--out", a.out, aligned], check=True)
        print(f"{a.out}: versionCode {a.version_code}, signed with {'a throwaway key' if a.new_key else ks}")
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
